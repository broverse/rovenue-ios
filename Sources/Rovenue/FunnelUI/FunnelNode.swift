// MARK: - Tree description

/// Every helper here mirrors `tree.rs` exactly; the two are a pair, and a
/// change to one without the other shows up as a contract failure.
private enum TreeFormat {
    static let indent = "  "

    /// Double-quote and escape, matching `q` in tree.rs.
    static func q(_ s: String) -> String {
        var out = "\""
        for c in s {
            switch c {
            case "\\": out += "\\\\"
            case "\"": out += "\\\""
            case "\n": out += "\\n"
            default: out.append(c)
            }
        }
        return out + "\""
    }

    /// An optional attribute, omitted entirely when absent. Absence is
    /// spelled ONE way — by not appearing.
    static func opt(_ key: String, _ value: String?) -> String {
        guard let v = value, !v.isEmpty else { return "" }
        return " \(key)=\(q(v))"
    }

    /// An option with no icon, in a question whose other options have one —
    /// `ABSENT_ICON` in tree.rs.
    static let absentIcon = "-"
    /// A grid's tile density on the question line — `DENSITY_*` in tree.rs.
    static let densityDense = "dense"
    static let densityRegular = "regular"

    /// An icon's plate, `+plate(#background/padding/radius)`, or nothing
    /// for a bare glyph — `plate` in tree.rs.
    static func plate(_ icon: RenderIcon) -> String {
        icon.plate.map { "+plate(\($0.background)/\($0.padding)/\($0.radius))" } ?? ""
    }

    /// SF Symbols' wire pack, between a pack and a name, and between a
    /// symbol and its fallback — `SF_PACK`, `GLYPH_KEY_SEPARATOR`,
    /// `FALLBACK_ARROW` in tree.rs.
    static let sfPack = "sf"
    static let glyphKeySeparator = ":"
    static let fallbackArrow = ">"

    /// A list icon's identity, `name` or `sf:<symbol>><pack>:<name>` —
    /// `icon_id` in tree.rs.
    static func iconId(_ icon: RenderIcon) -> String {
        guard let symbol = icon.systemSymbol else { return icon.name + weightMark(icon) }
        return "\(sfPack)\(glyphKeySeparator)\(symbol.name)\(fallbackArrow)\(icon.pack)\(glyphKeySeparator)\(icon.name)"
            + weightMark(icon)
    }

    /// `@<weight>` after an icon whose site names its own weight —
    /// `weight_mark` in tree.rs (spec F §7 G6).
    static func weightMark(_ icon: RenderIcon) -> String {
        icon.weight.map { "@\($0)" } ?? ""
    }

    /// An icon block's pack and name, plus an SF symbol's fallback and
    /// decided style — `icon_head` in tree.rs.
    static func iconHead(_ icon: RenderIcon) -> String {
        // Spec F §7 G6: an icon block names its site weight as its own key.
        let weight = icon.weight.map { " icon-weight=\($0)" } ?? ""
        guard let symbol = icon.systemSymbol else {
            return "pack=\(icon.pack) name=\(icon.name)" + weight
        }
        let secondary = symbol.secondary.map { "+\($0)" } ?? ""
        return "pack=\(sfPack) name=\(symbol.name) fallback=\(icon.pack)\(glyphKeySeparator)\(icon.name)"
            + " mode=\(symbol.mode)\(secondary) weight=\(symbol.weight) minOs=\(symbol.minOs ?? absentIcon)"
            + weight
    }

    /// A list icon's paint, `size/#color` then its plate — `paint` in tree.rs.
    static func paint(_ icon: RenderIcon) -> String {
        "\(icon.size)/\(icon.color)\(plate(icon))"
    }

    /// What a button, a purchase button or the CTA prints after its
    /// action, and only when there is something to print — `button_extras`
    /// in tree.rs: ` size=<name>:<minHeight>/<paddingX>x<paddingY>/<fontSize>/<iconSize>`
    /// for a size other than `md`, then ` icon=<position>:<icon>/<paint> gap=<gap>`
    /// for a drawn icon.
    static func buttonExtras(_ button: FunnelButtonParts) -> String {
        guard let sizeLook = button.sizeLook else { return "" }
        var out = ""
        if let size = button.size {
            out += " size=\(size)\(glyphKeySeparator)\(sizeLook.minHeight)/\(sizeLook.paddingX)x\(sizeLook.paddingY)"
                + "/\(sizeLook.fontSize)/\(sizeLook.iconSize)"
        }
        if let icon = button.icon, let position = button.iconPosition {
            out += " icon=\(position)\(glyphKeySeparator)\(iconId(icon))/\(paint(icon)) gap=\(sizeLook.iconGap)"
        }
        return out
    }

    /// A spring as the tree prints it, `ratio/stiffness/response/settle` —
    /// `spring` in tree.rs.
    static func spring(_ s: RenderSpring) -> String {
        "\(s.dampingRatio)/\(s.stiffness)/\(s.responseMs)/\(s.settleMs)"
    }

    /// ` motion=<parts>` for a node that carries motion, nothing otherwise —
    /// `motion_attr` in tree.rs: `enter(<preset>/<durationMs>/<delayMs>/<curve>:<spring>)`,
    /// `exit(<preset>/<durationMs>)`, `emphasis(<name>)`, `+`-joined.
    static func motionAttr(_ motion: RenderMotion?) -> String {
        guard let motion else { return "" }
        var parts: [String] = []
        if let enter = motion.enter {
            parts.append(
                "enter(\(enter.preset)/\(enter.durationMs)/\(enter.delayMs)/\(enter.curve)\(glyphKeySeparator)\(spring(enter.spring)))")
        }
        if let exit = motion.exit { parts.append("exit(\(exit.preset)/\(exit.durationMs))") }
        if let emphasis = motion.emphasis { parts.append("emphasis(\(emphasis))") }
        return parts.isEmpty ? "" : " motion=\(parts.joined(separator: "+"))"
    }

    /// The look line's carousel segment (spec CL §4.7, §6), once per look —
    /// `carousel_tokens` in tree.rs, same order and separators.
    static func carouselTokens(_ c: RenderCarouselLook) -> String {
        " carousel=\(c.neighbourScale)/\(c.neighbourOpacity),\(c.stackDepth)/\(c.stackOffset)/\(c.stackScaleStep)"
            + ",\(c.throwDistance)/\(c.throwTilt),\(c.swipeThreshold)/\(c.flingVelocity),\(c.pillFactor),\(c.barGap)"
            + ",\(c.indicatorPitch)/\(c.indicatorMargin)/\(c.overlayInset)"
            + ",\(c.counterPaddingX)x\(c.counterPaddingY)/\(c.counterWeight)/\(c.counterTextFactor)"
            + ",\(c.arrowSize)/\(c.arrowInset)/\(c.arrowFillOpacity),\(c.pauseSize)"
            + ",\(c.cardPadding)/\(c.cardBorderWidth)/\(c.cardShadow.y):\(c.cardShadow.blur):\(c.cardShadow.color)/\(c.cardElevation)"
            + ",\(c.marqueeSlowPxPerS)/\(c.marqueeNormalPxPerS)/\(c.marqueeFastPxPerS)"
    }

    /// Spec CL words the carousel line compares against — tree.rs's constants.
    static let carouselLayoutPeek = "peek"
    static let carouselIndicatorDots = "dots"
    static let carouselIndicatorBelow = "below"
    static let curveSmooth = "smooth"
    static let curveSnappy = "snappy"
    static let curveBouncy = "bouncy"
    /// The `en` chrome-copy row's slide and motion labels (`en_slide_labels`
    /// in chrome_copy.rs): the tree prints `labels=` only where a screen's
    /// differ. A tree-format constant — no drawer reads it.
    static let enPreviousSlide = "Previous slide"
    static let enNextSlide = "Next slide"
    static let enPauseMotion = "Pause animation"
    static let enPlayMotion = "Play animation"

    /// ` labels="<a>|<b>"` unless both are the `en` row's.
    static func slideLabels(_ a: String, _ b: String, en enA: String, _ enB: String) -> String {
        a == enA && b == enB ? "" : " labels=\(q("\(a)|\(b)"))"
    }

    /// A carousel line's spec-CL tokens, each only away from the
    /// absent-field default — `carousel_extras` in tree.rs, same order.
    static func carouselExtras(_ b: CarouselBlock, motion: RenderMotionTokens) -> String {
        var out = ""
        if b.layout != carouselLayoutPeek { out += " layout=\(b.layout)" }
        if let m = b.marquee {
            out += " marquee=\(m.pxPerS)/\(m.direction)" + slideLabels(m.pauseLabel, m.playLabel, en: enPauseMotion, enPlayMotion)
        }
        if let c = b.card {
            out += " card=\(c.style):r\(c.radius)/p\(c.padding)/\(c.background)"
            if let border = c.borderColor { out += "/b\(border)" }
            if let s = c.shadow { out += "/s\(s.y):\(s.blur):\(s.color)" }
            if let g = c.glass, let strength = c.strength { out += "/g\(strength):\(g.tint)" }
        }
        if let a = b.arrows {
            out += " arrows=\(a.position)" + slideLabels(a.previousLabel, a.nextLabel, en: enPreviousSlide, enNextSlide)
        }
        let named = [(curveSmooth, motion.smooth), (curveSnappy, motion.snappy), (curveBouncy, motion.bouncy)]
        switch named.first(where: { $0.1 == b.curve })?.0 {
        case curveSmooth?: break
        case let name?: out += " curve=\(name)"
        // Not a look spring: its numbers, never a hidden drift.
        case nil: out += " curve=\(spring(b.curve))"
        }
        if b.fadeMs != motion.normalMs { out += " fade=\(b.fadeMs)" }
        if b.bleed != 0 { out += " bleed=\(b.bleed)" }
        if !b.counterLabels.isEmpty { out += " counter=\(q(b.counterLabels.joined(separator: "|")))" }
        return out
    }

    /// The look line's motion segments — `motion_tokens` in tree.rs.
    static func motionTokens(_ m: RenderMotionTokens) -> String {
        let curve = { (points: [Int]) in points.map(String.init).joined(separator: ",") }
        return " motion=\(m.fastMs)/\(m.normalMs)/\(m.pageMs)/\(m.slowMs)/\(m.exitPercent)"
            + " springs=\(spring(m.smooth)),\(spring(m.snappy)),\(spring(m.bouncy))"
            + " curves=\(curve(m.fadeCurve))/\(curve(m.exitCurve))"
            + " travel=\(m.elementDistance)/\(m.pageDistance)/\(m.pushPercent)/\(m.pushDim)"
            + " scales=\(m.enterScale)/\(m.popScale)/\(m.pulseScale)"
            + " fadeThrough=\(m.fadeThroughScale)/\(m.fadeThroughSplit)"
            + " pulse=\(m.pulseCycles)/\(m.pulseMs)"
            + " stagger=\(m.cascadeStepMs)/\(m.cascadeMaxMs)/\(m.enterAtPercent)"
    }

    /// Appends `suffix` to the first line written to `out` since the UTF-8
    /// offset `start` — a node's own line, whichever arm drew it (its
    /// children follow on lines of their own) — `suffix_first_line` in tree.rs.
    static func suffixFirstLine(_ out: inout String, from start: Int, _ suffix: String) {
        guard !suffix.isEmpty else { return }
        let from = out.utf8.index(out.utf8.startIndex, offsetBy: start)
        guard let newline = out[from...].firstIndex(of: "\n") else { return }
        out.insert(contentsOf: suffix, at: newline)
    }

    /// The look line's new-element segment (spec NE §6), once per look and
    /// last — `elements_tokens` in tree.rs, same order and separators.
    static func elementsTokens(_ e: RenderElementsLook) -> String {
        let p = e.popup, c = e.countdown, l = e.loader, h = e.chart
        return " elements=popup:\(p.scrimOpacity)/\(p.sheetRadius)/\(p.dialogRadius)/\(p.dialogMaxWidth)/\(p.padding)"
            + "/\(p.closeSize)x\(p.closeHit)/\(p.exitArmMs)"
            + ",countdown:\(c.boxRadius)/\(c.boxPadding)/\(c.boxGap)/\(c.digitScale)/\(q(c.separator))/\(c.tabularDigits)"
            + "/\(c.daysFromMs)/\(c.hoursFromMs)/\(c.tickMs)"
            + ",loader:\(l.ringSize)/\(l.ringStroke)/\(l.barHeight)/\(l.barRadius)/\(l.stepRowHeight)/\(l.stepGap)"
            + ",chart:\(h.height)/\(h.strokeWidth)/\(h.markerRadius)/\(h.areaOpacity)/\(h.barRadius)/\(h.barGap)"
            + "/\(h.curve)x\(h.curveSamples)/\(h.yPad)"
            + ",lottie:\(e.lottie.visibleThreshold),announce:\(e.announceDebounceMs)"
    }

    /// An absent value on a new element's line — `ABSENT` in tree.rs.
    static let absent = dash
    /// A lottie with no explicit width — `schema::LOTTIE_WIDTH_FILL`.
    static let lottieWidthFill = "fill"

    /// An optional string, quoted, or `-` — `q_opt` in tree.rs.
    static func qOpt(_ s: String?) -> String { s.map(q) ?? absent }

    /// An optional number, or `-` — `n_opt` in tree.rs.
    static func nOpt(_ n: Int?) -> String { n.map(String.init) ?? absent }

    /// One unit's four words, `short-one|short-other|long-one|long-other`
    /// — `unit_words` in tree.rs.
    static func unitWords(_ w: RenderUnitWord) -> String {
        q("\(w.shortOne)|\(w.shortOther)|\(w.longOne)|\(w.longOther)")
    }

    static func line(_ depth: Int, _ body: String, into out: inout String) {
        out += String(repeating: indent, count: depth) + body + "\n"
    }

    /// ` width=<fit|fill>` and ` self=<start|center|end>` for a block that
    /// wrote either — `placement_attr` in tree.rs.
    static func placementAttr(_ style: RenderStyle?) -> String {
        guard let style else { return "" }
        var out = ""
        if let width = style.width { out += " width=\(width)" }
        if let alignSelf = style.alignSelf { out += " self=\(alignSelf)" }
        out += absoluteAttr(style) + borderAttr(style)
        if let degrees = style.rotation { out += " rotate=\(degrees)" }
        return out
    }

    /// An absolute block's placement — `absolute_attr` in tree.rs.
    static func absoluteAttr(_ style: RenderStyle) -> String {
        guard let position = style.position else { return "" }
        let n = { (v: Double?) in rustNumber(v ?? 0) }
        var out =
            " position=\(position) pin=\(n(style.pinX)),\(n(style.pinY))"
            + " inset=\(n(style.insetTop))/\(n(style.insetLeading))/\(n(style.insetBottom))/\(n(style.insetTrailing))"
        if style.shiftX != nil || style.shiftY != nil {
            out += " shift=\(n(style.shiftX)),\(n(style.shiftY))"
        }
        if let edges = style.safeAreaEdges, !edges.isEmpty {
            out += " safe=\(edges.joined(separator: ","))"
        }
        return out
    }

    /// ` border=<width>/<#color>/<dash>` for an AUTHORED border — `border_attr`.
    static func borderAttr(_ style: RenderStyle) -> String {
        guard let dash = style.borderStyle, let width = style.borderWidth, let color = style.borderColor
        else { return "" }
        return " border=\(width)/\(color)/\(dash)"
    }

    /// ` colors=<run>@<#hex>,…` — `colors_attr` in tree.rs.
    static func colorsAttr(_ segments: [RenderSegment]?) -> String {
        let runs = (segments ?? []).compactMap { s in s.color.map { "\(q(s.text))@\($0)" } }
        return runs.isEmpty ? "" : " colors=\(runs.joined(separator: ","))"
    }

    /// ` boxed=<run>,…` — `boxed_attr` in tree.rs (spec F §6 F4b).
    static func boxedAttr(_ segments: [RenderSegment]?) -> String {
        let runs = (segments ?? []).filter { $0.boxed == true }.map { q($0.text) }
        return runs.isEmpty ? "" : " boxed=\(runs.joined(separator: ","))"
    }

    /// An unset half of a two-part attribute — `DASH` in tree.rs.
    static let dash = "-"

    /// `glass/<blur>/<material>/<sat>/<tint>/<fallback>` — `glass_spelling`.
    static func glassSpelling(_ s: RenderSurface) -> String {
        "\(s.kind)/\(s.blurRadius)/\(s.iosMaterial)/\(s.saturation)/\(s.tint)/\(s.fallback)"
    }

    /// ` disabled=<#bg|->/<#text|->` — `disabled_attr` in tree.rs (spec F §6 F6).
    static func disabledAttr(_ background: String?, _ text: String?) -> String {
        if background == nil && text == nil { return "" }
        return " disabled=\(background ?? dash)/\(text ?? dash)"
    }

    /// An image's overlay — `overlay_attr` in tree.rs (spec F §6 F3).
    static func overlayAttr(_ overlay: RenderOverlay?) -> String {
        guard let o = overlay else { return "" }
        var out = " overlay=\(o.position)/\(o.width)/\(o.inset) overlay-text=\(q(o.text)) overlay-color=\(o.color)"
        if let bg = o.background { out += " overlay-plate=\(bg)" }
        if let s = o.surface { out += " overlay-surface=\(glassSpelling(s))" }
        if let i = o.icon { out += " overlay-icon=\(iconId(i))/\(paint(i))" }
        if let key = o.activityCheck { out += " overlay-activity=\(key)" }
        if let key = o.check { out += " overlay-check=\(key)" }
        out += opt("overlay-checking", o.checkingText)
        // Spec F §7 G5.
        if let a = o.align { out += " overlay-align=\(a)" }
        if o.paddingX != nil || o.paddingY != nil {
            out += " overlay-padding=\(o.paddingX.map(String.init) ?? dash)/\(o.paddingY.map(String.init) ?? dash)"
        }
        return out
    }

    /// A photo question's Spec F looks — `photo_looks_attr` in tree.rs.
    static func photoLooksAttr(_ p: RenderPhotoQuestion) -> String {
        var out = ""
        if let v = p.pickStyle { out += " pick-style=\(v)" }
        if let i = p.pickIcon { out += " pick-icon=\(iconId(i))/\(paint(i))" }
        if let v = p.changePosition { out += " change-at=\(v)" }
        if let s = p.changeSurface { out += " change-surface=\(glassSpelling(s))" }
        if let v = p.privacyPlacement { out += " privacy-placement=\(v)" }
        // Spec F §7 G1 / N1.
        if p.pickBackground != nil || p.pickColor != nil {
            out += " pick-paint=\(p.pickBackground ?? dash)/\(p.pickColor ?? dash)"
        }
        out += opt("camera-label", p.cameraLabel) + opt("library-label", p.libraryLabel)
        // Spec F §8 H7 / H8 / H11.
        if let b = p.answeredBorder { out += " answered-border=\(b.width)/\(b.color)" }
        if let o = p.pickOffset { out += " pick-offset=\(o.x)/\(o.y)" }
        if let g = p.pickGap { out += " pick-gap=\(g)" }
        return out
    }

    /// ` <key>=<x>/<y>` for an authored pair of insets — `insets_attr` in
    /// tree.rs (spec F §8 H1/H12).
    static func insetsAttr(_ key: String, _ insets: RenderInsets?) -> String {
        insets.map { " \(key)=\($0.x)/\($0.y)" } ?? ""
    }

    /// ` toggle-look=<k>:<v>,…` — `toggle_look_attr` in tree.rs (spec F §8 H4).
    static func toggleLookAttr(_ a: RenderToggleAppearance?) -> String {
        guard let a else { return "" }
        var parts: [String] = []
        if let c = a.background { parts.append("bg:\(c)") }
        if let c = a.color { parts.append("text:\(c)") }
        if let w = a.borderWidth, let c = a.borderColor { parts.append("border:\(w)/\(c)") }
        if let r = a.radius { parts.append("radius:\(r)") }
        let pads = [a.paddingTop, a.paddingRight, a.paddingBottom, a.paddingLeft]
        if pads.contains(where: { $0 != nil }) {
            parts.append("padding:" + pads.map { $0.map(String.init) ?? dash }.joined(separator: "/"))
        }
        return parts.isEmpty ? "" : " toggle-look=\(parts.joined(separator: ","))"
    }

    /// An accordion item's authored plate — `item_look_attr` in tree.rs.
    static func itemLookAttr(_ style: RenderStyle) -> String {
        let pads = [style.paddingTop, style.paddingRight, style.paddingBottom, style.paddingLeft]
        if style.background == nil && style.radius == nil && pads.allSatisfy({ $0 == nil }) { return "" }
        let n = { (v: Int?) in v.map(String.init) ?? dash }
        return " item-look=\(style.background ?? dash)/\(n(style.radius))/"
            + pads.map(n).joined(separator: "/")
    }

    /// ` surface=glass blur=<r>/<material> sat=<s> tint=<#> fallback=<#>` — `surface_attr`.
    static func surfaceAttr(_ surface: RenderSurface?) -> String {
        guard let s = surface else { return "" }
        return " surface=\(s.kind) blur=\(s.blurRadius)/\(s.iosMaterial) sat=\(s.saturation) tint=\(s.tint) fallback=\(s.fallback)"
    }

    /// A picture grid's tile style — `tile_style_attr`.
    static func tileStyleAttr(_ t: RenderTileStyle?) -> String {
        guard let t else { return "" }
        return " tileStyle=\(t.mediaAspect)/\(t.textPlacement)/\(t.scrim) ring=\(t.ringColor)/\(t.ringWidth)"
            + " indicator=\(t.indicator)/\(t.indicatorColor) radius=\(t.radius)"
            + " autoplay=\(onOff(t.videoAutoplay))/\(onOff(t.videoAutoplayOnCellular))"
            + (t.unselectedIndicator.map { " unselected=\($0)" } ?? "")
            + (t.descriptionPosition.map { " description=\($0)" } ?? "")
            + (t.indicatorGlyphColor.map { " indicator-glyph=\($0)" } ?? "")
            + insetsAttr("text-inset", t.textInset)
    }

    /// `url:"<url>"` / `photo:"<ref>"` — `media_spelling`.
    static func mediaSpelling(_ media: RenderMedia) -> String {
        switch media {
        case .url(let url): return "url:\(q(url))"
        case .photo(let ref): return "photo:\(q(ref))"
        }
    }

    /// One option sub-line — `option_line` in tree.rs.
    static func optionLine(_ o: RenderOption) -> String {
        let media = o.media.map { m in " media=\(m.kind):\(q(m.url))" + (m.poster.map { "/\(q($0))" } ?? "") } ?? ""
        let chips = o.chips ?? []
        let chipText =
            chips.isEmpty
            ? ""
            : " chips="
                + chips.map { c in
                    "\(c.corner):\(q(c.text))/\(c.color)/\(c.background)" + (c.icon.map { "+\(iconId($0))" } ?? "")
                        + (c.dot.map { "+dot(\($0))" } ?? "")
                }.joined(separator: ",")
        // Spec F §8 H9: a marked description.
        let description =
            o.descriptionSegments.flatMap { segments in
                o.description.map { " description=\(q($0))" + colorsAttr(segments) + boxedAttr(segments) }
            } ?? ""
        return "option value=\(q(o.value))\(media)\(chipText)\(description)"
    }

    /// Copy with checkout slots as one quoted string — `parts_spelling`.
    static func partsSpelling(_ parts: [RenderCopyPart]) -> String {
        q(
            parts.map { part in
                switch part {
                case .text(let text): return text
                case .slot(let name): return "{{\(name)}}"
                }
            }.joined())
    }

    /// A carousel's slide line and an accordion item's open state — tree.rs.
    static let slideLine = "slide"
    static let open = "open"
    static let closed = "closed"

    /// ` glass=<regular|prominent>` — `glass_attr` in tree.rs.
    static func glassAttr(_ glass: String?) -> String {
        glass.map { " glass=\($0)" } ?? ""
    }

    /// A progress line's switches, and its label when it prints none —
    /// `ON`/`OFF`/`YES`/`NO`/`PROGRESS_NO_LABEL` in tree.rs.
    static let on = "on"
    static let off = "off"
    static let yes = "yes"
    static let no = "no"
    static let progressNoLabel = "label=none"
    /// The pinned header region's line — `HEADER_LINE` in tree.rs.
    static let headerLine = "header"
    /// The screen-pinned layer's line — `OVERLAY_LINE` in tree.rs.
    static let overlayLine = "overlay"

    static func onOff(_ value: Bool) -> String { value ? on : off }
}

private func describe(_ node: FunnelNode, depth: Int, motion: RenderMotionTokens, into out: inout String) {
    let start = out.utf8.count
    describeLine(node, depth: depth, motion: motion, into: &out)
    TreeFormat.suffixFirstLine(
        &out, from: start, TreeFormat.placementAttr(node.style) + TreeFormat.motionAttr(node.motion))
}

private func describeLine(_ node: FunnelNode, depth: Int, motion: RenderMotionTokens, into out: inout String) {
    switch node {
    case .heading(let b):
        TreeFormat.line(
            depth,
            "heading level=\(b.level) text=\(TreeFormat.q(b.text))\(TreeFormat.colorsAttr(b.segments))\(TreeFormat.boxedAttr(b.segments))",
            into: &out)
    case .text(let b):
        TreeFormat.line(
            depth,
            "text text=\(TreeFormat.q(b.text))\(TreeFormat.colorsAttr(b.segments))\(TreeFormat.boxedAttr(b.segments))",
            into: &out)
    case .image(let b) where b.photoRef != nil:
        TreeFormat.line(
            depth,
            "image photo=\(TreeFormat.q(b.photoRef ?? ""))\(TreeFormat.opt("alt", b.alt))\(b.bleed ? " bleed" : "")"
                + TreeFormat.overlayAttr(b.overlay),
            into: &out)
    case .image(let b):
        TreeFormat.line(
            depth,
            "image url=\(TreeFormat.q(b.url))\(TreeFormat.opt("alt", b.alt))\(b.bleed ? " bleed" : "")"
                + TreeFormat.overlayAttr(b.overlay),
            into: &out)
    case .video(let b):
        TreeFormat.line(
            depth, "video url=\(TreeFormat.q(b.url))\(TreeFormat.opt("poster", b.poster))", into: &out)
    case .button(let b):
        TreeFormat.line(
            depth,
            "button variant=\(b.variant) chromeless=\(b.chromeless) enabled=\(b.enabled) label=\(TreeFormat.q(b.label)) action=\(b.actionPath)\(TreeFormat.buttonExtras(b)) haptic=\(b.haptic)\(TreeFormat.glassAttr(b.glass))"
                + TreeFormat.disabledAttr(b.disabledBackground, b.disabledText),
            into: &out)
    case .spacer(let b):
        TreeFormat.line(depth, "spacer size=\(b.size)\(b.flex ? " flex" : "")", into: &out)
    case .icon(let b):
        TreeFormat.line(
            depth,
            "icon \(TreeFormat.iconHead(b.glyph)) size=\(b.glyph.size) color=\(b.glyph.color)\(TreeFormat.plate(b.glyph)) layers=\(b.glyph.layers.count)",
            into: &out)
    case .divider:
        TreeFormat.line(depth, "divider", into: &out)
    case .activity:
        TreeFormat.line(depth, "activity", into: &out)
    case .review(let b):
        let rating = b.rating.map { " rating=\($0)" } ?? ""
        TreeFormat.line(
            depth,
            "review\(rating) quote=\(TreeFormat.q(b.quote))\(TreeFormat.opt("author", b.author))",
            into: &out)
    case .gallery(let b):
        TreeFormat.line(depth, "gallery columns=\(b.columns) urls=\(b.urls.count)", into: &out)
    case .stack(let b, let children):
        // Placement, only when it is not today's top-left packed group.
        let align =
            b.alignX == RenderLayout.alignLeft && b.alignY == RenderLayout.alignTop
            ? "" : " align=\(b.alignX)/\(b.alignY)"
        let spread = b.distribute == RenderLayout.distributePacked ? "" : " distribute=\(b.distribute)"
        TreeFormat.line(
            depth,
            "stack direction=\(b.direction) gap=\(b.gap)\(align)\(spread)\(b.clip ? " clip" : "")\(TreeFormat.surfaceAttr(b.surface))",
            into: &out)
        for child in children { describe(child, depth: depth + 1, motion: motion, into: &out) }
    case .progress(let b):
        // Its colours and geometry print: dedicated fields, not a
        // role-mapped style, and nothing else pins them.
        let label = b.labelText.map { "label=\(TreeFormat.q($0))" } ?? TreeFormat.progressNoLabel
        let segments = b.segmentGap.map { " seg=\($0)" } ?? ""
        let dashes = b.dashLength.flatMap { on in b.dashGap.map { " dash=\(on)/\($0)" } } ?? ""
        let switches: String =
            "progress style=\(b.barStyle) bar=\(TreeFormat.onOff(b.showBar)) back=\(TreeFormat.onOff(b.showBack))"
        let enabled: String = b.backEnabled ? TreeFormat.yes : TreeFormat.no
        let head: String = "\(switches) icon=\(b.backIcon) \(label) back-enabled=\(enabled)"
        let bar: String =
            "\(b.current)/\(b.total) height=\(b.barHeight)/\(rustNumber(b.barRadius))\(segments)\(dashes)"
        let chrome: String =
            "back-size=\(b.backSize)/\(b.backGlyphSize) label-size=\(b.labelSize)/\(b.labelOpacity) row-gap=\(b.rowGap)"
        let colors: String =
            "active=\(b.activeColor) track=\(b.trackColor)" + (b.currentColor.map { " current=\($0)" } ?? "")
        TreeFormat.line(depth, "\(head) \(bar) \(chrome) \(colors)", into: &out)
    case .question(let b):
        let selected = b.selected.isEmpty ? "" : " selected=\(b.selected.joined(separator: ","))"
        let contact =
            b.contactFields.isEmpty
            ? ""
            : " contactFields="
                + b.contactFields.map { "\($0.key)(\(TreeFormat.q($0.placeholder))\(invalidAttr($0.invalid)))" }
                .joined(separator: ",")
        let labels =
            b.options.isEmpty
            ? "" : " labels=\(b.options.map { TreeFormat.q($0.label) }.joined(separator: ","))"
        let icons =
            b.options.contains { $0.icon != nil }
            ? " icons="
                + b.options.map { option in
                    option.icon.map { "\(TreeFormat.iconId($0))/\(TreeFormat.paint($0))" } ?? TreeFormat.absentIcon
                }.joined(separator: ",")
            : ""
        // A grid prints its column count and tile anatomy; a list and chips
        // have neither — `arrangement` in tree.rs.
        let arrangement =
            b.tile.map {
                "layout=\(b.layout) columns=\(b.columns) tile=\($0.rawValue) density=\(b.dense ? TreeFormat.densityDense : TreeFormat.densityRegular)"
            } ?? "layout=\(b.layout)"
        let photo =
            b.photo.map { p in
                " pick=\(TreeFormat.q(p.pickLabel)) hint=\(TreeFormat.q(p.pickHint)) change=\(TreeFormat.q(p.changeLabel))"
                    + TreeFormat.opt("privacy", p.privacyLabel) + " sources=\(p.sources.joined(separator: ","))"
                    + (p.photo.map { " photo=\(TreeFormat.mediaSpelling($0))" } ?? "")
                    + TreeFormat.photoLooksAttr(p)
            } ?? ""
        TreeFormat.line(
            depth,
            "question kind=\(b.kind) required=\(b.required) options=\(b.options.count) \(arrangement) multiple=\(b.multiple)\(labels)\(icons)\(selected)\(contact)\(invalidAttr(b.invalid))\(TreeFormat.tileStyleAttr(b.tileStyle))\(photo)",
            into: &out)
        if b.options.contains(where: { $0.media != nil || !($0.chips ?? []).isEmpty || $0.descriptionSegments != nil }) {
            for option in b.options { TreeFormat.line(depth + 1, TreeFormat.optionLine(option), into: &out) }
        }
    case .packageList(let b):
        let selected = b.selectedIdentifier.map { " selected=\($0)" } ?? ""
        TreeFormat.line(
            depth,
            "packageList layout=\(b.layout) packages=\(b.packages.count)\(selected) highlight=\(b.highlight)/\(b.highlightFill)"
                + (b.secondaryTextSize.map { " secondary-size=\($0)" } ?? "")
                // Spec F §8 H1–H3.
                + TreeFormat.insetsAttr("row-padding", b.rowPadding)
                + (b.rowGap.map { " row-gap=\($0)" } ?? "")
                + (b.captionTextSize.map { " caption-size=\($0)" } ?? "")
                + (b.indicatorDotColor.map { " indicator-dot=\($0)" } ?? ""),
            into: &out)
        for package in b.packages {
            let badge =
                package.badge.map {
                    " badge=\(TreeFormat.q($0.text)) tone=\($0.background)/\($0.color)"
                } ?? ""
            TreeFormat.line(
                depth + 1,
                "package id=\(package.identifier) price=\(TreeFormat.q(package.localizedPrice))"
                    + "\(TreeFormat.opt("title", package.localizedTitle))\(badge)\(TreeFormat.opt("caption", package.caption))"
                    + (package.icon.map { " icon=\(TreeFormat.iconId($0))/\(TreeFormat.paint($0))" } ?? "")
                    + (package.inlineBadge.map {
                        " inline-badge=\(TreeFormat.q($0.text)) inline-tone=\($0.background)/\($0.color)"
                    } ?? "")
                    + TreeFormat.opt("price-text", package.priceText) + TreeFormat.opt("price-suffix", package.priceSuffix)
                    + (package.periodText.map { " period-text=\(TreeFormat.q($0))" } ?? ""),
                into: &out)
        }
    case .comparisonTable(let b):
        let highlight = b.highlight.map { " highlight=\($0)" } ?? ""
        TreeFormat.line(
            depth,
            "comparisonTable columns=\(b.columns.map(TreeFormat.q).joined(separator: ","))\(highlight)",
            into: &out)
        for row in b.rows {
            let cells = row.cells.map { cell in
                cell.text.map { "\(cell.kind)(\(TreeFormat.q($0)))" } ?? cell.kind
            }
            TreeFormat.line(
                depth + 1,
                "row label=\(TreeFormat.q(row.label)) cells=\(cells.joined(separator: ","))",
                into: &out)
        }
    case .featureList(let b):
        TreeFormat.line(
            depth, "featureList items=\(b.items.count) iconColumn=\(b.iconColumn)", into: &out)
        for item in b.items {
            // An SF feature names its symbol and its fallback, as a list icon does.
            let name = item.glyph.flatMap { $0.systemSymbol == nil ? nil : TreeFormat.iconId($0) } ?? item.icon
            let named = name.isEmpty ? item.iconKind : "\(item.iconKind)(\(TreeFormat.q(name)))"
            let icon =
                item.glyph.map {
                    "\(named)/\($0.size)x\($0.layers.count)/\($0.color)\(TreeFormat.plate($0))"
                } ?? named
            TreeFormat.line(
                depth + 1,
                "feature icon=\(icon) title=\(TreeFormat.q(item.title))\(TreeFormat.opt("body", item.body))",
                into: &out)
        }
    case .purchaseButton(let b):
        TreeFormat.line(
            depth,
            "purchaseButton variant=\(b.variant) enabled=\(b.enabled) label=\(TreeFormat.q(b.label)) action=\(b.actionPath)\(TreeFormat.buttonExtras(b)) haptic=\(b.haptic)\(TreeFormat.glassAttr(b.glass))"
                + TreeFormat.disabledAttr(b.disabledBackground, b.disabledText),
            into: &out)
    case .stickyFooter(_, let children):
        TreeFormat.line(depth, "stickyFooter", into: &out)
        for child in children { describe(child, depth: depth + 1, motion: motion, into: &out) }
    case .expressCheckout(_, let children):
        TreeFormat.line(depth, "expressCheckout", into: &out)
        for child in children { describe(child, depth: depth + 1, motion: motion, into: &out) }
    case .check(let b):
        TreeFormat.line(
            depth,
            "check key=\(b.key) display=\(b.display) phase=\(b.phase) checking=\(TreeFormat.q(b.checkingLabel))"
                + TreeFormat.opt("badge", b.badgeText)
                + (b.photo.map { " photo=\(TreeFormat.mediaSpelling($0))" } ?? "")
                + checkLooksAttr(b),
            into: &out)
        for step in b.steps {
            TreeFormat.line(
                depth + 1, "step id=\(step.id) label=\(TreeFormat.q(step.label)) status=\(step.status)", into: &out)
        }
    case .cardCheckout(let b):
        let toggle =
            b.toggle.map { t in
                " toggle=\(TreeFormat.q(t.label))/\(t.initiallyOpen ? TreeFormat.open : TreeFormat.closed)"
                    + (t.icon.map { "+\(TreeFormat.iconId($0))" } ?? "")
                    + TreeFormat.toggleLookAttr(t.appearance)
                    // Spec F §9 I2.
                    + (t.align.map { " toggle-align=\($0)" } ?? "")
                    + (t.chevron == false ? " toggle-chevron=off" : "")
            } ?? ""
        let summary =
            b.summary.map { s in
                let row = { (p: [RenderCopyPart]?) in p.map(TreeFormat.partsSpelling) ?? "-" }
                return " summary=\(row(s.productLine))|\(row(s.totalLabel))"
            } ?? ""
        let brands = b.brands.isEmpty ? "" : " brands=\(b.brands.joined(separator: ","))"
        let f = b.fields
        TreeFormat.line(
            depth,
            "cardCheckout\(b.taxRows ? " taxRows" : "")\(brands) enabled=\(b.enabled) pay=\(TreeFormat.partsSpelling(b.payLabel))"
                + "\(toggle) email=\(TreeFormat.q(b.email.label))/\(TreeFormat.q(b.email.placeholder))\(summary)"
                + TreeFormat.opt("note", b.note) + TreeFormat.opt("legal", b.legal)
                + " fields=\(f.background)/\(f.border)/\(f.radius)/\(f.labelColor)/\(f.textColor)/\(f.placeholderColor)"
                + " unavailable=\(TreeFormat.q(b.unavailable))"
                + TreeFormat.opt("note-collapsed", b.noteWhenCollapsed)
                // Spec F §9 I3.
                + TreeFormat.colorsAttr(b.noteWhenCollapsedSegments)
                + TreeFormat.boxedAttr(b.noteWhenCollapsedSegments)
                + (b.noteTextSize.map { " note-size=\($0)" } ?? "")
                + (b.brandsWhenCollapsed ? " brands-collapsed" : ""),
            into: &out)
    case .carousel(let b, let children):
        // The indicator slot is always printed (spec CL §6): today's
        // `dots=on:…`/`dots=off`, or `indicator=<style>@<position>:…`.
        let slot: String
        if let i = b.indicator {
            let marks = "\(i.activeColor)/\(i.inactiveColor)/\(i.size)"
            slot = i.style == TreeFormat.carouselIndicatorDots && i.position == TreeFormat.carouselIndicatorBelow
                ? "dots=\(TreeFormat.on):\(marks)" : "indicator=\(i.style)@\(i.position):\(marks)"
        } else {
            slot = "dots=\(TreeFormat.off)"
        }
        TreeFormat.line(
            depth,
            "carousel w=\(b.itemWidth) align=\(b.align) gap=\(b.gap) \(slot)"
                + TreeFormat.carouselExtras(b, motion: motion)
                + (b.autoplayMs.map { " autoplay=\($0)" } ?? "") + (b.looping ? " loop" : ""),
            into: &out)
        for child in children {
            TreeFormat.line(depth + 1, TreeFormat.slideLine, into: &out)
            describe(child, depth: depth + 2, motion: motion, into: &out)
        }
    case .accordion(let b, let bodies):
        TreeFormat.line(
            depth,
            "accordion \(b.mode) \(b.chevron) gap=\(b.gap) title=\(b.titleColor)/\(b.titleSize)"
                + ((b.expandedLabel == nil && b.collapsedLabel == nil)
                    ? ""
                    : " state-labels=\(TreeFormat.q(b.expandedLabel ?? "")),\(TreeFormat.q(b.collapsedLabel ?? ""))"),
            into: &out)
        for (item, body) in zip(b.items, bodies) {
            TreeFormat.line(
                depth + 1,
                "item \(TreeFormat.q(item.title)) \(item.open ? TreeFormat.open : TreeFormat.closed)\(TreeFormat.placementAttr(item.style))"
                    + TreeFormat.itemLookAttr(item.style),
                into: &out)
            for child in body { describe(child, depth: depth + 2, motion: motion, into: &out) }
        }
    // Spec NE §6: every resolved number and string — `describe_element_line`
    // in tree.rs.
    case .countdown(let b):
        let u = b.units
        TreeFormat.line(
            depth,
            "countdown key=\(b.key) mode=\(b.mode) display=\(b.display) atZero=\(b.atZero)"
                + " deadline=\(TreeFormat.nOpt(b.deadlineMs)) duration=\(TreeFormat.nOpt(b.durationMs)) expired=\(b.expired)"
                + " label=\(TreeFormat.qOpt(b.label)) expiredText=\(TreeFormat.q(b.expiredText))"
                + " units=d:\(TreeFormat.unitWords(u.days));h:\(TreeFormat.unitWords(u.hours))"
                + ";m:\(TreeFormat.unitWords(u.minutes));s:\(TreeFormat.unitWords(u.seconds))"
                + " one=\(b.pluralOne.map(String.init).joined(separator: ","))",
            into: &out)
    case .popup(let b, let children):
        TreeFormat.line(
            depth,
            "popup presentation=\(b.presentation) trigger=\(b.trigger) delay=\(b.delayMs) once=\(b.oncePerSession)"
                + " close=\(b.closeButton) scrim=\(b.scrimDismiss) open=\(b.open)"
                + " label=\(TreeFormat.qOpt(b.label)) closeLabel=\(TreeFormat.q(b.closeLabel))",
            into: &out)
        for child in children { describe(child, depth: depth + 1, motion: motion, into: &out) }
    case .loader(let b):
        TreeFormat.line(
            depth,
            "loader duration=\(b.durationMs) indicator=\(b.indicator) percent=\(b.showPercent) hold=\(b.holdCta)"
                + " progress=elapsed*1000/\(b.durationMs)",
            into: &out)
        for step in b.steps {
            TreeFormat.line(depth + 1, "step ends=\(step.endsMs) label=\(TreeFormat.q(step.label))", into: &out)
        }
    case .lottie(let b):
        TreeFormat.line(
            depth,
            "lottie url=\(TreeFormat.q(b.url)) aspect=\(b.aspectPermille) width=\(b.width.map(String.init) ?? TreeFormat.lottieWidthFill)"
                + " loop=\(b.looping) speed=\(b.speedPercent) still=\(b.still) poster=\(TreeFormat.qOpt(b.poster))"
                + " label=\(TreeFormat.qOpt(b.label)) playback=\(b.playback)",
            into: &out)
    case .chart(let b):
        let points = b.points.isEmpty
            ? TreeFormat.absent
            : b.points.map { $0.map(String.init).joined(separator: ",") }.joined(separator: ";")
        TreeFormat.line(
            depth,
            "chart kind=\(b.kind) fill=\(b.fill) points=\(points)"
                + " start=\(TreeFormat.qOpt(b.startValue)) end=\(TreeFormat.qOpt(b.endValue))"
                + " startLabel=\(TreeFormat.qOpt(b.startLabel)) endLabel=\(TreeFormat.qOpt(b.endLabel))"
                + " marker=\(TreeFormat.qOpt(b.marker)) unit=\(TreeFormat.qOpt(b.unit)) label=\(TreeFormat.q(b.label))",
            into: &out)
        for bar in b.bars {
            TreeFormat.line(
                depth + 1,
                "bar height=\(bar.height) highlight=\(bar.highlight) label=\(TreeFormat.q(bar.label)) value=\(TreeFormat.q(bar.value))",
                into: &out)
        }
    case .cookieConsent(let b):
        let categories = b.categories.map { "\($0.id):\(TreeFormat.q($0.label))" }.joined(separator: ",")
        let labels = [b.acceptAllLabel, b.onlyNecessaryLabel, b.customizeLabel, b.saveLabel, b.policyLabel]
            .joined(separator: "|")
        TreeFormat.line(
            depth,
            "cookieConsent display=\(b.display) customize=\(b.customize) title=\(TreeFormat.q(b.title)) body=\(TreeFormat.q(b.body))"
                + " categories=\(categories) policy=\(TreeFormat.qOpt(b.policyUrl)) labels=\(TreeFormat.q(labels))",
            into: &out)
    case .cta(let c):
        TreeFormat.line(
            depth,
            "cta enabled=\(c.enabled) label=\(TreeFormat.q(c.label)) action=\(c.actionPath)\(TreeFormat.buttonExtras(c)) haptic=\(c.haptic)"
                + TreeFormat.disabledAttr(c.disabledBackground, c.disabledText),
            into: &out)
    }
}

/// A check's Spec F looks, each only when authored — the `looks` run of
/// the check arm in tree.rs.
private func checkLooksAttr(_ b: CheckBlock) -> String {
    var out = ""
    if b.showPhoto == false { out += " show-photo=off" }
    if let h = b.rowHeight { out += " row-height=\(h)" }
    if let d = b.divider { out += " divider=\(d)" }
    if let s = b.surface {
        out += " check-surface=\(s.background ?? TreeFormat.dash)/\(s.radius.map(String.init) ?? TreeFormat.dash)"
    }
    out += TreeFormat.opt("cta-checking", b.ctaCheckingLabel)
    // Spec F §8 H10.
    if let n = b.indicatorSize { out += " indicator-size=\(n)" }
    if let c = b.pendingColor { out += " pending=\(c)" }
    // Spec F §9 I4.
    if let c = b.pendingLabelColor { out += " pending-label=\(c)" }
    return out
}

