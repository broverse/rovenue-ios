//  FunnelNode.swift — the seam between decoding and drawing.
//
//  SwiftUI view trees cannot be introspected, so the cross-platform
//  contract cannot be checked against built views. It is checked HERE
//  instead: `funnelNodes(for:)` is the mapping decision, and the exhaustive
//  switch that turns a FunnelNode into a view (FunnelNodeView) is what makes
//  the compiler guarantee every case has one. Neither covers the failure
//  mode alone.
//
//  The description format is specified in
//  docs/superpowers/specs/2026-09-20-flows-native-renderers-design.md §5
//  and the expected text is generated by
//  packages/funnel-core-rs/src/tree.rs. A mismatch is a bug in THIS file —
//  never "fixed" by regenerating the expected file.

import Foundation

indirect enum FunnelNode: Equatable, Sendable {
    case heading(HeadingBlock)
    case text(TextBlock)
    case image(ImageBlock)
    case video(VideoBlock)
    case button(ButtonBlock)
    case spacer(SpacerBlock)
    case icon(IconBlock)
    case divider(DividerBlock)
    case activity(ActivityBlock)
    case review(ReviewBlock)
    case gallery(GalleryBlock)
    case stack(StackBlock, [FunnelNode])
    case question(QuestionBlock)
    case packageList(PackageListBlock)
    case comparisonTable(ComparisonTableBlock)
    case featureList(FeatureListBlock)
    case purchaseButton(PurchaseButtonBlock)
    case stickyFooter(StickyFooterBlock, [FunnelNode])
    case expressCheckout(ExpressCheckoutBlock, [FunnelNode])
    case cta(RenderCta)
}

/// One node per drawn block, in order, with the CTA last. A block this
/// build does not know never reaches here — `LenientBlocks` already
/// dropped it — and a block that draws nothing gets no node.
func funnelNodes(for screen: RenderScreen) -> [FunnelNode] {
    var nodes = screen.blocks.compactMap(funnelNode(for:))
    if let cta = screen.cta {
        nodes.append(.cta(cta))
    }
    return nodes
}

/// nil for a block that draws NOTHING: a media block with no source
/// (validator warning `MEDIA_WITHOUT_SOURCE`). The resolver decides
/// "blank" once (`render::media_url`): it sends an unsourced url as ""
/// and only the sourced gallery tiles, so emptiness is the whole test
/// here. Dropping it here, rather than drawing an empty view for it, is
/// what lets the tree contract see it — the views below never receive one.
private func funnelNode(for block: RenderBlock) -> FunnelNode? {
    switch block {
    case .heading(let b): return .heading(b)
    case .text(let b): return .text(b)
    case .image(let b): return b.url.isEmpty ? nil : .image(b)
    case .video(let b): return b.url.isEmpty ? nil : .video(b)
    case .button(let b): return .button(b)
    case .spacer(let b): return .spacer(b)
    case .icon(let b): return .icon(b)
    case .divider(let b): return .divider(b)
    case .activity(let b): return .activity(b)
    case .review(let b): return .review(b)
    case .gallery(let b): return b.urls.isEmpty ? nil : .gallery(b)
    case .stack(let b): return .stack(b, b.children.compactMap(funnelNode(for:)))
    case .question(let b): return .question(b)
    case .packageList(let b): return .packageList(b)
    case .comparisonTable(let b): return .comparisonTable(b)
    case .featureList(let b): return .featureList(b)
    case .purchaseButton(let b): return .purchaseButton(b)
    case .stickyFooter(let b): return .stickyFooter(b, b.children.compactMap(funnelNode(for:)))
    case .expressCheckout(let b):
        return .expressCheckout(b, b.children.compactMap(funnelNode(for:)))
    }
}

// MARK: - Identity

/// A drawn node and the identity `ForEach` keeps its view state under.
struct IdentifiedFunnelNode: Identifiable {
    let id: String
    let node: FunnelNode
}

/// `nodes`, each identified by its block (`type:blockId`), never by its
/// position: a `visibleWhen` block appearing ABOVE a focused field shifts
/// every position after it, and a positional identity would rebuild the
/// field — dropping focus and the caret mid-word. A block with no id falls
/// back to its position. Mirrors the web's `funnelNodeKey` and sdk-kotlin's
/// FunnelReconcile (type + blockId).
func identified(_ nodes: [FunnelNode]) -> [IdentifiedFunnelNode] {
    nodes.enumerated().map { index, node in
        IdentifiedFunnelNode(id: node.identity ?? "#\(index)", node: node)
    }
}

/// The CTA's identity: there is at most one per screen.
private let ctaIdentity = "cta"

extension FunnelNode {
    /// `type:blockId`, "cta" for the CTA, or nil for a block with no id.
    fileprivate var identity: String? {
        let pair: (type: String, blockId: String)
        switch self {
        case .heading(let b): pair = ("heading", b.blockId)
        case .text(let b): pair = ("text", b.blockId)
        case .image(let b): pair = ("image", b.blockId)
        case .video(let b): pair = ("video", b.blockId)
        case .button(let b): pair = ("button", b.blockId)
        case .spacer(let b): pair = ("spacer", b.blockId)
        case .icon(let b): pair = ("icon", b.blockId)
        case .divider(let b): pair = ("divider", b.blockId)
        case .activity(let b): pair = ("activity", b.blockId)
        case .review(let b): pair = ("review", b.blockId)
        case .gallery(let b): pair = ("gallery", b.blockId)
        case .stack(let b, _): pair = ("stack", b.blockId)
        case .question(let b): pair = ("question", b.blockId)
        case .packageList(let b): pair = ("packageList", b.blockId)
        case .comparisonTable(let b): pair = ("comparisonTable", b.blockId)
        case .featureList(let b): pair = ("featureList", b.blockId)
        case .purchaseButton(let b): pair = ("purchaseButton", b.blockId)
        case .stickyFooter(let b, _): pair = ("stickyFooter", b.blockId)
        case .expressCheckout(let b, _): pair = ("expressCheckout", b.blockId)
        case .cta: return ctaIdentity
        }
        return pair.blockId.isEmpty ? nil : "\(pair.type):\(pair.blockId)"
    }
}

// MARK: - Tree description

/// Every helper here mirrors `tree.rs` exactly; the two are a pair, and a
/// change to one without the other shows up as a contract failure.
private enum TreeFormat {
    static let indent = "  "

    /// Double-quote and escape, matching `q` in tree.rs.
    static func q(_ s: String) -> String {
        var out = "\""
        for c in s {
            switch c {
            case "\\": out += "\\\\"
            case "\"": out += "\\\""
            case "\n": out += "\\n"
            default: out.append(c)
            }
        }
        return out + "\""
    }

    /// An optional attribute, omitted entirely when absent. Absence is
    /// spelled ONE way — by not appearing.
    static func opt(_ key: String, _ value: String?) -> String {
        guard let v = value, !v.isEmpty else { return "" }
        return " \(key)=\(q(v))"
    }

    /// An option with no icon, in a question whose other options have one —
    /// `ABSENT_ICON` in tree.rs.
    static let absentIcon = "-"
    /// A grid's tile density on the question line — `DENSITY_*` in tree.rs.
    static let densityDense = "dense"
    static let densityRegular = "regular"

    /// An icon's plate, `+plate(#background/padding/radius)`, or nothing
    /// for a bare glyph — `plate` in tree.rs.
    static func plate(_ icon: RenderIcon) -> String {
        icon.plate.map { "+plate(\($0.background)/\($0.padding)/\($0.radius))" } ?? ""
    }

    /// SF Symbols' wire pack, between a pack and a name, and between a
    /// symbol and its fallback — `SF_PACK`, `GLYPH_KEY_SEPARATOR`,
    /// `FALLBACK_ARROW` in tree.rs.
    static let sfPack = "sf"
    static let glyphKeySeparator = ":"
    static let fallbackArrow = ">"

    /// A list icon's identity, `name` or `sf:<symbol>><pack>:<name>` —
    /// `icon_id` in tree.rs.
    static func iconId(_ icon: RenderIcon) -> String {
        guard let symbol = icon.systemSymbol else { return icon.name }
        return "\(sfPack)\(glyphKeySeparator)\(symbol.name)\(fallbackArrow)\(icon.pack)\(glyphKeySeparator)\(icon.name)"
    }

    /// An icon block's pack and name, plus an SF symbol's fallback and
    /// decided style — `icon_head` in tree.rs.
    static func iconHead(_ icon: RenderIcon) -> String {
        guard let symbol = icon.systemSymbol else { return "pack=\(icon.pack) name=\(icon.name)" }
        let secondary = symbol.secondary.map { "+\($0)" } ?? ""
        return "pack=\(sfPack) name=\(symbol.name) fallback=\(icon.pack)\(glyphKeySeparator)\(icon.name)"
            + " mode=\(symbol.mode)\(secondary) weight=\(symbol.weight) minOs=\(symbol.minOs ?? absentIcon)"
    }

    /// A list icon's paint, `size/#color` then its plate — `paint` in tree.rs.
    static func paint(_ icon: RenderIcon) -> String {
        "\(icon.size)/\(icon.color)\(plate(icon))"
    }

    /// What a button, a purchase button or the CTA prints after its
    /// action, and only when there is something to print — `button_extras`
    /// in tree.rs: ` size=<name>:<minHeight>/<paddingX>x<paddingY>/<fontSize>/<iconSize>`
    /// for a size other than `md`, then ` icon=<position>:<icon>/<paint> gap=<gap>`
    /// for a drawn icon.
    static func buttonExtras(_ button: FunnelButtonParts) -> String {
        guard let sizeLook = button.sizeLook else { return "" }
        var out = ""
        if let size = button.size {
            out += " size=\(size)\(glyphKeySeparator)\(sizeLook.minHeight)/\(sizeLook.paddingX)x\(sizeLook.paddingY)"
                + "/\(sizeLook.fontSize)/\(sizeLook.iconSize)"
        }
        if let icon = button.icon, let position = button.iconPosition {
            out += " icon=\(position)\(glyphKeySeparator)\(iconId(icon))/\(paint(icon)) gap=\(sizeLook.iconGap)"
        }
        return out
    }

    static func line(_ depth: Int, _ body: String, into out: inout String) {
        out += String(repeating: indent, count: depth) + body + "\n"
    }
}

private func describe(_ node: FunnelNode, depth: Int, into out: inout String) {
    switch node {
    case .heading(let b):
        TreeFormat.line(depth, "heading level=\(b.level) text=\(TreeFormat.q(b.text))", into: &out)
    case .text(let b):
        TreeFormat.line(depth, "text text=\(TreeFormat.q(b.text))", into: &out)
    case .image(let b):
        TreeFormat.line(
            depth,
            "image url=\(TreeFormat.q(b.url))\(TreeFormat.opt("alt", b.alt))\(b.bleed ? " bleed" : "")",
            into: &out)
    case .video(let b):
        TreeFormat.line(
            depth, "video url=\(TreeFormat.q(b.url))\(TreeFormat.opt("poster", b.poster))", into: &out)
    case .button(let b):
        TreeFormat.line(
            depth,
            "button variant=\(b.variant) enabled=\(b.enabled) label=\(TreeFormat.q(b.label)) action=\(b.actionPath)\(TreeFormat.buttonExtras(b))",
            into: &out)
    case .spacer(let b):
        TreeFormat.line(depth, "spacer size=\(b.size)\(b.flex ? " flex" : "")", into: &out)
    case .icon(let b):
        TreeFormat.line(
            depth,
            "icon \(TreeFormat.iconHead(b.glyph)) size=\(b.glyph.size) color=\(b.glyph.color)\(TreeFormat.plate(b.glyph)) layers=\(b.glyph.layers.count)",
            into: &out)
    case .divider:
        TreeFormat.line(depth, "divider", into: &out)
    case .activity:
        TreeFormat.line(depth, "activity", into: &out)
    case .review(let b):
        let rating = b.rating.map { " rating=\($0)" } ?? ""
        TreeFormat.line(
            depth,
            "review\(rating) quote=\(TreeFormat.q(b.quote))\(TreeFormat.opt("author", b.author))",
            into: &out)
    case .gallery(let b):
        TreeFormat.line(depth, "gallery columns=\(b.columns) urls=\(b.urls.count)", into: &out)
    case .stack(let b, let children):
        TreeFormat.line(depth, "stack direction=\(b.direction) gap=\(b.gap)", into: &out)
        for child in children { describe(child, depth: depth + 1, into: &out) }
    case .question(let b):
        let selected = b.selected.isEmpty ? "" : " selected=\(b.selected.joined(separator: ","))"
        let contact =
            b.contactFields.isEmpty
            ? ""
            : " contactFields="
                + b.contactFields.map { "\($0.key)(\(TreeFormat.q($0.placeholder)))" }
                .joined(separator: ",")
        let labels =
            b.options.isEmpty
            ? "" : " labels=\(b.options.map { TreeFormat.q($0.label) }.joined(separator: ","))"
        let icons =
            b.options.contains { $0.icon != nil }
            ? " icons="
                + b.options.map { option in
                    option.icon.map { "\(TreeFormat.iconId($0))/\(TreeFormat.paint($0))" } ?? TreeFormat.absentIcon
                }.joined(separator: ",")
            : ""
        // A grid prints its column count and tile anatomy; a list and chips
        // have neither — `arrangement` in tree.rs.
        let arrangement =
            b.tile.map {
                "layout=\(b.layout) columns=\(b.columns) tile=\($0.rawValue) density=\(b.dense ? TreeFormat.densityDense : TreeFormat.densityRegular)"
            } ?? "layout=\(b.layout)"
        TreeFormat.line(
            depth,
            "question kind=\(b.kind) required=\(b.required) options=\(b.options.count) \(arrangement) multiple=\(b.multiple)\(labels)\(icons)\(selected)\(contact)",
            into: &out)
    case .packageList(let b):
        let selected = b.selectedIdentifier.map { " selected=\($0)" } ?? ""
        TreeFormat.line(
            depth,
            "packageList layout=\(b.layout) packages=\(b.packages.count)\(selected) highlight=\(b.highlight)/\(b.highlightFill)",
            into: &out)
        for package in b.packages {
            let badge =
                package.badge.map {
                    " badge=\(TreeFormat.q($0.text)) tone=\($0.background)/\($0.color)"
                } ?? ""
            TreeFormat.line(
                depth + 1,
                "package id=\(package.identifier) price=\(TreeFormat.q(package.localizedPrice))"
                    + "\(badge)\(TreeFormat.opt("caption", package.caption))"
                    + (package.icon.map { " icon=\(TreeFormat.iconId($0))/\(TreeFormat.paint($0))" } ?? ""),
                into: &out)
        }
    case .comparisonTable(let b):
        let highlight = b.highlight.map { " highlight=\($0)" } ?? ""
        TreeFormat.line(
            depth,
            "comparisonTable columns=\(b.columns.map(TreeFormat.q).joined(separator: ","))\(highlight)",
            into: &out)
        for row in b.rows {
            let cells = row.cells.map { cell in
                cell.text.map { "\(cell.kind)(\(TreeFormat.q($0)))" } ?? cell.kind
            }
            TreeFormat.line(
                depth + 1,
                "row label=\(TreeFormat.q(row.label)) cells=\(cells.joined(separator: ","))",
                into: &out)
        }
    case .featureList(let b):
        TreeFormat.line(
            depth, "featureList items=\(b.items.count) iconColumn=\(b.iconColumn)", into: &out)
        for item in b.items {
            // An SF feature names its symbol and its fallback, as a list icon does.
            let name = item.glyph.flatMap { $0.systemSymbol == nil ? nil : TreeFormat.iconId($0) } ?? item.icon
            let named = name.isEmpty ? item.iconKind : "\(item.iconKind)(\(TreeFormat.q(name)))"
            let icon =
                item.glyph.map {
                    "\(named)/\($0.size)x\($0.layers.count)/\($0.color)\(TreeFormat.plate($0))"
                } ?? named
            TreeFormat.line(
                depth + 1,
                "feature icon=\(icon) title=\(TreeFormat.q(item.title))\(TreeFormat.opt("body", item.body))",
                into: &out)
        }
    case .purchaseButton(let b):
        TreeFormat.line(
            depth,
            "purchaseButton variant=\(b.variant) enabled=\(b.enabled) label=\(TreeFormat.q(b.label)) action=\(b.actionPath)\(TreeFormat.buttonExtras(b))",
            into: &out)
    case .stickyFooter(_, let children):
        TreeFormat.line(depth, "stickyFooter", into: &out)
        for child in children { describe(child, depth: depth + 1, into: &out) }
    case .expressCheckout(_, let children):
        TreeFormat.line(depth, "expressCheckout", into: &out)
        for child in children { describe(child, depth: depth + 1, into: &out) }
    case .cta(let c):
        TreeFormat.line(
            depth,
            "cta enabled=\(c.enabled) label=\(TreeFormat.q(c.label)) action=\(c.actionPath)\(TreeFormat.buttonExtras(c))",
            into: &out)
    }
}

/// The screen's shared look, one line — `describe_look` in `tree.rs`.
/// Field order and separators are fixed by the Rust describer.
private func describeLook(_ l: RenderLook, depth: Int, into out: inout String) {
    let headings = l.headingSizes.map(String.init).joined(separator: ",")
    TreeFormat.line(
        depth,
        "look pad=\(l.pagePaddingX)/\(l.pagePaddingTop)/\(l.pagePaddingBottom) gap=\(l.blockGap)"
            + " text=\(l.textSize)/\(l.textWeight)/\(l.lineHeight)"
            + " heading=\(headings)/\(l.headingWeight) muted=\(l.mutedTextSize)"
            + " weights=\(l.labelWeight)/\(l.emphasisWeight)"
            + " button=\(l.buttonMinHeight)/\(l.buttonPaddingX)x\(l.buttonPaddingY)/\(l.buttonFontSize)/\(l.buttonFontWeight)"
            + " link=\(l.linkFontSize)/\(l.linkMinHeight)"
            + " card=\(l.cardPadding)/\(l.cardGap)/\(l.cardRadius)"
            + " row=\(l.rowPaddingX)x\(l.rowPaddingY)/\(l.rowGap)/\(l.indicatorSize)/\(l.indicatorCornerRadius)/\(l.indicatorGap)"
            + " border=\(l.borderWidth)/\(l.selectedBorderWidth)"
            + " activity=\(l.activitySize)/\(l.activityStroke)"
            + " field=\(l.fieldMinHeight)/\(l.fieldPaddingX)x\(l.fieldPaddingY)/\(l.longTextMinHeight)"
            + " scale=\(l.scaleCellMinHeight)/\(l.scaleGap) star=\(l.starSize)"
            + " slider=\(l.sliderTrackHeight)/\(l.sliderThumbSize)"
            + " press=\(l.pressScale)/\(l.rowPressScale)/\(l.pressMs)"
            + " badge=\(l.badgeFontSize)/\(l.badgeWeight)/\(l.badgePaddingX)x\(l.badgePaddingY)/\(l.badgeRadius)/\(l.badgeOffsetY)"
            + " pack=\(l.packIconSize)/\(l.packTitleSize)/\(l.packRibbonHeight)"
            + " table=\(l.tableValueColumnWidth)/\(l.tableRowPaddingY)/\(l.tableHeaderSize)/\(l.tableHeaderWeight)/\(l.tableCheckSize)"
            + " feature=\(l.featureIconSize)/\(l.featureIconGap)/\(l.featureItemGap)"
            + " tile=\(l.tileGap)/\(l.tileLabelGap)/\(l.tileRadius)/\(l.tileMinHeight)/\(l.tilePadding)"
            + "/\(l.tileIconSize)/\(l.tileLabelLines)/\(l.tilePaddingDense)/\(l.tileLabelSizeDense)"
            + " chip=\(l.chipGap)/\(l.chipPaddingX)x\(l.chipPaddingY)/\(l.chipRadius)"
            + " gallery=\(l.galleryGap)"
            + " colors=\(l.text),\(l.accent),\(l.card),\(l.border),\(l.muted),\(l.onAccent)"
            + ",\(l.success),\(l.onSuccess),\(l.tableHighlight)",
        into: &out)
}

/// `num_or_dash` in tree.rs: a number as Rust's `f64::to_string` prints it
/// (no `.0` on a whole number, the shortest round-trip otherwise), or `-`
/// when absent — the line is positional, so absence is never omitted.
private func numOrDash(_ value: Double?) -> String {
    guard let v = value else { return "-" }
    if v == v.rounded(), let whole = Int64(exactly: v) { return String(whole) }
    return "\(v)"
}

/// The page background's line, right after `look` — `describe_background`
/// in `tree.rs`.
private func describeBackground(_ b: RenderBackground, depth: Int, into out: inout String) {
    let value2 = b.value2.map(TreeFormat.q) ?? "-"
    TreeFormat.line(
        depth,
        "background kind=\(b.kind) value=\(TreeFormat.q(b.value)) value2=\(value2)"
            + " angle=\(numOrDash(b.angle)) opacity=\(numOrDash(b.opacity))"
            + (b.scrim.map { " scrim=\($0.edge)/\($0.color)/\($0.opacity)/\($0.extent)" } ?? "")
            + TreeFormat.opt("poster", b.poster),
        into: &out)
}

/// The screen's drawer copy line, right after `look`/`background` —
/// `describe_copy` in `tree.rs`: fixed order, the three contact
/// placeholders last (name, email, phone).
private func describeCopy(_ c: RenderChromeCopy, depth: Int, into out: inout String) {
    TreeFormat.line(
        depth,
        "copy positionOf=\(TreeFormat.q(c.positionOf)) selected=\(TreeFormat.q(c.selected))"
            + " checked=\(TreeFormat.q(c.checked)) unchecked=\(TreeFormat.q(c.unchecked))"
            + " contact=\(TreeFormat.q(c.contactName)),\(TreeFormat.q(c.contactEmail)),\(TreeFormat.q(c.contactPhone))"
            + " table=\(TreeFormat.q(c.included)),\(TreeFormat.q(c.notIncluded))",
        into: &out)
}

/// The screen's tree description, byte-identical to what
/// `funnel_core::tree::describe_screen` produces for the same input.
func describeFunnelTree(funnel: String, screen: RenderScreen) -> String {
    var out = ""
    let autoAdvanceMs = screen.autoAdvanceMs.map { " autoAdvanceMs=\($0)" } ?? ""
    let permission = screen.permission.map { " permission=\($0)" } ?? ""
    TreeFormat.line(
        0,
        "screen \(funnel)/\(screen.screenId) index=\(screen.index) total=\(screen.total) transition=\(screen.transition)\(autoAdvanceMs)\(permission)",
        into: &out)
    describeLook(screen.look, depth: 1, into: &out)
    if let background = screen.background {
        describeBackground(background, depth: 1, into: &out)
    }
    describeCopy(screen.copy, depth: 1, into: &out)
    for node in funnelNodes(for: screen) {
        describe(node, depth: 1, into: &out)
    }
    return out
}
