/// `invalid_attr` in tree.rs: ` invalid=<kind>`, plus `:<bound>` for a
/// range reason, printed as `numOrDash` prints a number; nothing when the
/// answer is usable.
private func invalidAttr(_ reason: RenderInvalidReason?) -> String {
    guard let reason else { return "" }
    let bound = (reason.min ?? reason.max).map { ":\(numOrDash($0))" } ?? ""
    return " invalid=\(reason.kind)\(bound)"
}

/// `num_or_dash` in tree.rs: a number as Rust's `f64::to_string` prints it
/// (no `.0` on a whole number, the shortest round-trip otherwise), or `-`
/// when absent — the line is positional, so absence is never omitted.
private func numOrDash(_ value: Double?) -> String {
    value.map(rustNumber) ?? "-"
}

/// A number as Rust's `f64::to_string` prints it: no `.0` on a whole
/// number, the shortest round-trip otherwise.
func rustNumber(_ v: Double) -> String {
    if v == v.rounded(), let whole = Int64(exactly: v) { return String(whole) }
    return "\(v)"
}

/// The screen line's layout attributes, each only away from today's page —
/// `screen_layout_attrs` in tree.rs: ` safe-area=off`, ` status-bar=off`,
/// ` layout=<dir>/<x>/<y>/<distribute>`, ` gap=<n>` (authored, or not the
/// rhythm's), ` pad=<t>/<r>/<b>/<l>` (a side not the look's).
private func screenLayoutAttrs(_ screen: RenderScreen) -> String {
    var out = ""
    if !screen.safeArea { out += " safe-area=off" }
    if !screen.statusBar { out += " status-bar=off" }
    let l = screen.layout
    if l.direction != RenderLayout.directionVertical || l.alignX != RenderLayout.alignLeft
        || l.alignY != RenderLayout.alignTop || l.distribute != RenderLayout.distributePacked
    {
        out += " layout=\(l.direction)/\(l.alignX)/\(l.alignY)/\(l.distribute)"
    }
    if l.gapAuthored || l.gap != RenderLayout.rhythmBodyGap { out += " gap=\(rustNumber(l.gap))" }
    let p = screen.padding
    if p != RenderPadding(look: screen.look) {
        out += " pad=\(rustNumber(p.top))/\(rustNumber(p.right))/\(rustNumber(p.bottom))/\(rustNumber(p.left))"
    }
    return out
}

/// The page background's line, right after `look` — `describe_background`
/// in `tree.rs`.
private func describeBackground(_ b: RenderBackground, depth: Int, into out: inout String) {
    let value2 = b.value2.map(TreeFormat.q) ?? "-"
    TreeFormat.line(
        depth,
        "background kind=\(b.kind) value=\(TreeFormat.q(b.value)) value2=\(value2)"
            + " angle=\(numOrDash(b.angle)) opacity=\(numOrDash(b.opacity))"
            + (b.scrim.map { " scrim=\($0.edge)/\($0.color)/\($0.opacity)/\($0.extent)" } ?? "")
            + TreeFormat.opt("poster", b.poster),
        into: &out)
}

/// The screen's drawer copy line, right after `look`/`background` —
/// `describe_copy` in `tree.rs`: fixed order, the three contact
/// placeholders last (name, email, phone).
private func describeCopy(_ c: RenderChromeCopy, depth: Int, into out: inout String) {
    TreeFormat.line(
        depth,
        "copy positionOf=\(TreeFormat.q(c.positionOf)) selected=\(TreeFormat.q(c.selected))"
            + " checked=\(TreeFormat.q(c.checked)) unchecked=\(TreeFormat.q(c.unchecked))"
            + " contact=\(TreeFormat.q(c.contactName)),\(TreeFormat.q(c.contactEmail)),\(TreeFormat.q(c.contactPhone))"
            + " table=\(TreeFormat.q(c.included)),\(TreeFormat.q(c.notIncluded))"
            + " invalid=\(TreeFormat.q(c.invalidEmail)),\(TreeFormat.q(c.invalidPhone)),\(TreeFormat.q(c.invalidNumber))"
            + ",\(TreeFormat.q(c.numberTooLow)),\(TreeFormat.q(c.numberTooHigh)),\(TreeFormat.q(c.invalidDate))"
            + ",\(TreeFormat.q(c.tooLong))",
        into: &out)
}

/// The screen's tree description, byte-identical to what
/// `funnel_core::tree::describe_screen` produces for the same input.
func describeFunnelTree(funnel: String, screen: RenderScreen) -> String {
    var out = ""
    let motion = screen.look.motion
    let autoAdvanceMs = screen.autoAdvanceMs.map { " autoAdvanceMs=\($0)" } ?? ""
    let permission = screen.permission.map { " permission=\($0)" } ?? ""
    // Each printed only away from its default — `describe_screen` in tree.rs.
    let cascade = screen.cascade ? " cascade=on" : ""
    let haptics = screen.haptics ? "" : " haptics=off"
    // Last, and only on a screen resolved in the dark palette.
    let scheme = screen.scheme.map { " scheme=\($0)" } ?? ""
    TreeFormat.line(
        0,
        "screen \(funnel)/\(screen.screenId) index=\(screen.index) total=\(screen.total) transition=\(screen.transition)\(cascade)\(haptics)\(autoAdvanceMs)\(permission)\(screenLayoutAttrs(screen))\(scheme)",
        into: &out)
    describeLook(screen.look, depth: 1, into: &out)
    if let background = screen.background {
        describeBackground(background, depth: 1, into: &out)
    }
    describeCopy(screen.copy, depth: 1, into: &out)
    // The pinned header region, before the body; its line heads its
    // blocks the way `stickyFooter` heads its children.
    let header = funnelHeaderNodes(for: screen)
    if !header.isEmpty {
        TreeFormat.line(1, TreeFormat.headerLine, into: &out)
        for node in header { describe(node, depth: 2, motion: motion, into: &out) }
    }
    // The screen-pinned layer, headed the same way, before the body.
    let overlay = funnelOverlayNodes(for: screen)
    if !overlay.isEmpty {
        TreeFormat.line(1, TreeFormat.overlayLine, into: &out)
        for node in overlay { describe(node, depth: 2, motion: motion, into: &out) }
    }
    for node in funnelNodes(for: screen) {
        describe(node, depth: 1, motion: motion, into: &out)
    }
    return out
}
